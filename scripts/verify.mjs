// Static + gate-branch verification against dist/. Exit 0 only if every check passes.
import fs from 'node:fs'; import path from 'node:path'; import { pathToFileURL } from 'node:url';
const D = 'dist'; let pass = 0, fail = 0;
const ok = (c, m) => { c ? pass++ : fail++; console.log((c ? 'PASS ' : 'FAIL ') + m); };
const read = (p) => fs.readFileSync(p, 'utf8');
const walk = (d) => fs.readdirSync(d, { recursive: true }).map((f) => path.join(d, f)).filter((f) => fs.statSync(f).isFile());
const imp = (f) => import(pathToFileURL(path.resolve(D, 'js', f)).href);

// 1. logo present in dist and referenced with correct relative paths
const html = read(`${D}/index.html`);
const refs = [...html.matchAll(/(?:src|href)="([^"#:]+?)"/g)].map((m) => m[1]).filter((r) => !r.startsWith('http') && !r.startsWith('//'));
for (const r of refs) ok(fs.existsSync(path.join(D, r)), `dist/${r} exists (referenced by index.html)`);
ok(html.includes('src="brand/sprl-logo-512.png"') && html.includes('src="brand/sprl-logo-96.png"'), 'index.html references logo via relative brand/ path');
ok(fs.existsSync(`${D}/brand/sprl-logo-full.png`), 'source logo explicitly copied to dist/brand/sprl-logo-full.png');
ok(/viewBox="0 0 32 32"/.test(read(`${D}/favicon.svg`)), 'favicon.svg is 32x32');

// 2. palette rule
for (const f of walk(D).filter((f) => /\.(css|js|html)$/.test(f) && !f.endsWith('tokens.css'))) {
  const t = read(f).replace(/href="#[a-z]+"/g, '').replace(/<meta name="theme-color"[^>]*>/, '');
  ok(!/#[0-9a-fA-F]{3,8}\b/.test(t) && !/\b(rgb|rgba|hsl|hsla)\(/.test(t), `no colour literal in ${f}`);
  ok(!/\d(ch)\b/.test(t), `no ch units in ${f}`);
}

// 3. no dates / clocks in shipped page code
for (const f of [`${D}/index.html`, ...walk(`${D}/js`)]) {
  const t = read(f).replace(/_PATH = '[^']*'/g, '').replace(/http:\/\/www\.w3\.org\/2000\/svg/g, '');
  ok(!/\b(19|20)\d{2}\b/.test(t) && !/\b\d{1,2}:\d{2}\b/.test(t) && !/\b(January|February|March|April|June|July|August|September|October|November|December)\b/i.test(t) && !/toLocale(Date|Time)String|new Date\(|Date\.now\(\)/.test(t), `no dates/timestamps in ${f}`);
}

// 4. repo hygiene
ok(!fs.existsSync('CLAUDE.md') && !fs.existsSync('.claude'), 'no CLAUDE.md, no .claude/');
const own = ['README.md', 'LICENSE', 'docs/whitepaper.md', 'package.json', ...walk('src'), ...walk('scripts').filter((f) => !f.endsWith('verify.mjs'))];
ok(own.every((f) => !/claude|anthropic|co-authored|generated by ai|ai-generated/i.test(read(f))), 'no AI attribution in repo files');

// 5. register / gates / link rule / scanner
const { createRegister, createStore, hrefOf, handleOf, isStated } = await imp('register.js');
const { GATES, evaluateGates } = await imp('gates.js');
const { scanText } = await imp('scan.js');
const reg0 = createRegister();
ok(hrefOf(reg0.x) === 'https://x.com/SpiralApp' && handleOf(reg0.x) === 'SpiralApp', 'X stated -> href, handle derived');
ok(hrefOf(reg0.github) === null, 'GitHub absent -> no href');
const REAL = 'So11111111111111111111111111111111111111112';
const A = evaluateGates(createRegister());
const st = createStore(); st.set('ca', { state: 'stated', value: REAL }); const B = evaluateGates(st.get());
console.log('  gates (CA absent):', JSON.stringify(A)); console.log('  gates (CA stated):', JSON.stringify(B));
ok(A['ca-slot'] === 'inert' && A['own-row'] === 'logo-placeholder', 'branch CA ABSENT: slot inert, own row = brand-logo placeholder');
ok(B['ca-slot'] === 'copy-live' && B['own-row'] === 'live-pinned', 'branch CA STATED: slot live, own row pinned');
ok(A.market === B.market && A.market === 'polling', 'market gate identical in both CA branches');
st.set('ca', { state: 'stated', value: '0x' + 'ab'.repeat(20) }); ok(st.record('ca').state === 'unconfirmed', 'non-address-shaped CA degrades to unconfirmed');
const caReg = st.get(); caReg.ca = { state: 'stated', value: REAL };
ok(scanText(`see ${REAL}`, caReg)[0].verdict === 'ca-exempt', 'scanner: stated CA exempt');
const hexV = scanText('0x' + 'ab'.repeat(20), caReg)[0];
ok(hexV && hexV.verdict === 'unmatched', 'scanner: 0x hex not blanket-rejected, matched against registry (warn only)');
ok(scanText('plain prose only', caReg).length === 0, 'scanner: prose passes');

// 6. market + own loaders with mock fetch
const { loadMarket, pickTop, withBackoff } = await imp('market.js');
const { loadOwn, composeBoard } = await imp('own.js');
const boosts = [
  ...Array.from({ length: 12 }, (_, i) => ({ chainId: 'solana', tokenAddress: `T${i}`.padEnd(32, 'x'), totalAmount: i * 10 })),
  { chainId: 'ethereum', tokenAddress: 'E1', totalAmount: 9999 }, { chainId: 'solana', tokenAddress: 'T11'.padEnd(32, 'x'), totalAmount: 5 },
];
const top = pickTop(boosts); ok(top.length === 10 && top.every((b) => b.chainId === 'solana') && top[0].totalAmount === 110, 'market: solana only, top 10 by totalAmount, deduped');
const calls = [];
const mk = (extra = {}) => async (url) => { calls.push(url); await 0;
  if (url.includes('token-boosts')) return { ok: true, json: async () => boosts };
  if (url.includes('/tokens/v1/solana/')) { const a = decodeURIComponent(url.split('/').pop()); return { ok: true, json: async () => [{ chainId: 'solana', baseToken: { address: a, symbol: a.slice(0, 3), name: 'n' }, priceUsd: '1.5', priceChange: { h24: 2 }, volume: { h24: 100 }, liquidity: { usd: 50 }, info: { imageUrl: null } }] }; }
  if (extra.latest && url.includes('/latest/dex/tokens/')) return extra.latest(url);
  if (extra.pump && url.includes('pump.fun')) return extra.pump(url);
  throw new Error('unexpected ' + url); };
const rowsA = await loadMarket(createRegister(), { fetchImpl: mk(), sleepFn: async () => {} });
const callsA = [...calls]; calls.length = 0;
const rowsB = await loadMarket(caReg, { fetchImpl: mk(), sleepFn: async () => {} });
ok(rowsA.length === 10 && JSON.stringify(callsA) === JSON.stringify(calls), 'market: CA state has zero effect on requests made');
const sleeps = []; let n = 0;
const v = await withBackoff(async () => { if (n++ < 2) throw new Error('x'); return 'ok'; }, { sleepFn: async (ms) => sleeps.push(ms) });
ok(v === 'ok' && sleeps.join() === '800,1600', 'backoff: exponential 800,1600');
let started = 0, startedBeforeFirstResolve = 0;
const gate = {}; const slow = (name) => () => { started++; return new Promise((res) => { gate[name] = res; }); };
const ownP = loadOwn(caReg, { fetchImpl: async (u) => (u.includes('pump.fun') ? slow('pump')() : slow('dex')()), fallbackLogo: 'brand/x.png' });
await new Promise((r) => setTimeout(r, 10)); startedBeforeFirstResolve = started;
gate.pump({ ok: true, json: async () => ({ image_uri: 'https://img/pump.png', symbol: 'SPRL', name: 'SPRL' }) });
gate.dex({ ok: true, json: async () => ({ pairs: [{ chainId: 'solana', baseToken: { address: REAL, symbol: 'SP', name: 'Sprl' }, priceUsd: '0.01', volume: { h24: 10 }, liquidity: { usd: 5 }, priceChange: { h24: -3 } }, { chainId: 'solana', baseToken: { address: REAL, symbol: 'BIG', name: 'Big' }, priceUsd: '0.02', volume: { h24: 900 }, liquidity: { usd: 7 }, priceChange: { h24: 4 }, info: { imageUrl: 'https://img/dex.png' } }] }) });
const own1 = await ownP;
ok(startedBeforeFirstResolve === 2, 'own: dex + pump.fun both in flight before either resolves (parallel)');
ok(own1.symbol === 'BIG' && own1.price === 0.02, 'own: pair chosen by volume.h24 desc');
ok(own1.logos[0] === 'https://img/pump.png' && own1.logos[1] === 'https://img/dex.png' && own1.logos[2] === 'brand/x.png', 'own: logo chain pump.fun -> dex -> brand/');
const ownDead = await loadOwn(caReg, { fetchImpl: async (u) => { if (u.includes('pump.fun')) throw new Error('down'); return { ok: true, json: async () => ({ pairs: [{ chainId: 'solana', baseToken: { address: REAL, symbol: 'Q', name: 'Q' }, priceUsd: '1', volume: { h24: 1 }, liquidity: { usd: 1 }, priceChange: { h24: 0 } }] }) }; } });
ok(ownDead && ownDead.ok && ownDead.sources.pump === 'rejected', 'own: pump.fun failure never blocks dex data');
ok((await loadOwn(createRegister())) === null, 'own: CA absent -> no fetch, null');
const board = composeBoard(own1, rowsB.map((r, i) => (i === 2 ? { ...r, address: REAL } : r)), REAL);
ok(board.length === 10 && board[0] === own1 && board.filter((r) => r.address === REAL).length === 1, 'board: own pinned row #1, duplicate removed from trending');

// 7. copy overlap vs reference (2-grams), stop-word-only bigrams excluded
const refJs = '.tmp-ref/index.js';
if (fs.existsSync(refJs)) {
  const stop = new Set('a an the and or but of to in on at by for with from as is are was be it its this that these those you your we our they their i he she not no do does can will just so if then than into out up'.split(' '));
  const words = (s) => s.toLowerCase().replace(/[^a-z' ]+/g, ' ').split(/\s+/).filter((w) => w.length > 1);
  const bg = (s) => { const o = new Set(); for (const seg of s.split(/[.!?|\n]+/)) { const w = words(seg); for (let i = 0; i < w.length - 1; i++) if (!(stop.has(w[i]) && stop.has(w[i + 1]))) o.add(w[i] + ' ' + w[i + 1]); } return o; };
  const refText = [...read(refJs).matchAll(/"([^"\\]{18,400})"|`([^`\\$]{18,400})`/g)].map((m) => m[1] || m[2]).filter((s) => /\s/.test(s) && /[a-z]{3}/i.test(s)).join(' . ');
  const jsLits = walk(`${D}/js`).flatMap((f) => [...read(f).matchAll(/'([A-Z][A-Za-z ,.\u00b7-]{10,120})'/g)].map((m) => m[1])).filter((s) => /\s/.test(s) && !/^(row|\.|\[)/.test(s)).join(' . ');
  const mine = html.replace(/<(script|style)[\s\S]*?<\/\1>/g, ' ').replace(/<[^>]+>/g, ' ').replace(/&\w+;/g, ' ') + ' . ' + jsLits;
  const R = bg(refText), shared = [...bg(mine)].filter((g) => R.has(g));
  ok(shared.length === 0, `copy: zero shared 2-grams with reference (${shared.length}${shared.length ? ': ' + shared.join(' | ') : ''})`);
} else console.log('SKIP reference 2-gram check (no .tmp-ref/index.js)');

console.log(`\nGATES: ${GATES.length} defined (${GATES.map((g) => g.id).join(', ')}); ${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
